"""Shared reader for the balance tools: asset index, field types and [Range]/[Min] limits, from the repo only.

Used by make_delta.py (validation) and export_kitlab_data.py (the Kit Lab page's data). Reads Assets/_Game/Data/**/*.asset
and Assets/_Game/Scripts/**/*.cs; never writes. A stopgap for a schema generated by Unity reflection (see BL-184): the
C# is parsed with regexes, so a field declared in an unusual way is reported as unknown rather than guessed.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "Assets" / "_Game" / "Data"
SCRIPTS = ROOT / "Assets" / "_Game" / "Scripts"

# Mirror of BalanceBook.DeniedFields (Assets/_Game/Scripts/Balance/BalanceBook.cs). Keep in sync.
DENIED = {
    "AllowedClasses", "PeckSlotPreEquippedBy", "SignaturePreEquippedBy", "Category", "BotRole", "AccentKey",
    "TerrainTraversal", "JumpTier", "CastMotion", "Retired",   # AbilityBaseSO
    "Subclass",                                                  # PassiveAbilitySO
    "FreshBiteShare",                                            # EnforcerPassiveSO (the game plays no food bite)
    "MaxPlayers", "TargetingMode", "LoadoutMode",                # MatchConfigSO
}

NAME = re.compile(r"^  m_Name: (.+)$", re.M)
CLS = re.compile(r"^  m_EditorClassIdentifier: .*?([A-Za-z0-9_]+)\s*$", re.M)
SCALAR = re.compile(r"^  ([A-Za-z_][A-Za-z0-9_]*): (-?[0-9.eE+-]+|true|false)\s*$", re.M)
GUID = re.compile(r"guid: ([0-9a-f]{32})")
CLASS_DECL = re.compile(
    r"^[ \t]*(?:public|internal|private|protected)?[ \t]*(?:(?:abstract|sealed|static|partial)[ \t]+)*"
    r"class[ \t]+(\w+)[ \t]*(?::[ \t]*([\w.]+))?", re.M)
FIELD_DECL = re.compile(r"((?:\[[^\]\n]*\]\s*)*)public\s+(?!static|const|readonly)([\w.<>\[\]]+)\s+(\w+)\s*(=|;)")
ENUM_DECL = re.compile(r"\benum\s+(\w+)")
NUM = r"(-?[0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?)f?"
RANGE = re.compile(r"Range\(\s*" + NUM + r"\s*,\s*" + NUM + r"\s*\)")
MIN = re.compile(r"\bMin\(\s*" + NUM + r"\s*\)")
PRIMS = {"float": "float", "int": "int", "bool": "bool", "byte": "int", "short": "int"}


class Field:
    def __init__(self, kind, lo=None, hi=None):
        self.kind, self.lo, self.hi = kind, lo, hi   # kind: float|int|bool|enum|other


def _scan_sources():
    classes, enums = {}, set()
    for p in SCRIPTS.rglob("*.cs"):
        t = p.read_text(encoding="utf-8", errors="replace")
        enums.update(ENUM_DECL.findall(t))
        for m in CLASS_DECL.finditer(t):
            name, base = m.group(1), (m.group(2) or "").split(".")[-1]
            if name not in classes or base:
                classes[name] = (base, t, m.start())
    return classes, enums


_CLASSES = _ENUMS = None


def class_fields(cls):
    """Public fields of a ScriptableObject class and its bases: {name: Field}. Nearest declaration wins."""
    global _CLASSES, _ENUMS
    if _CLASSES is None:
        _CLASSES, _ENUMS = _scan_sources()
    out, seen = {}, set()
    while cls and cls in _CLASSES and cls not in seen:
        seen.add(cls)
        base, text, start = _CLASSES[cls]
        # body = from this class to the next class declaration in the same file
        nxt = [m.start() for m in CLASS_DECL.finditer(text) if m.start() > start]
        body = text[start:(nxt[0] if nxt else len(text))]
        for attrs, typ, name, _ in FIELD_DECL.findall(body):
            if name in out:
                continue
            t = typ.split(".")[-1]
            kind = PRIMS.get(t, "enum" if t in _ENUMS else "other")
            lo = hi = None
            r = RANGE.search(attrs)
            if r:
                lo, hi = float(r.group(1)), float(r.group(2))
            m = MIN.search(attrs)
            if m:
                lo = float(m.group(1))
            out[name] = Field(kind, lo, hi)
        cls = base
    return out


class Asset:
    def __init__(self, path, text):
        self.path, self.text = path, text
        self.name = NAME.search(text).group(1).strip()
        m = CLS.search(text)
        self.cls = m.group(1) if m else ""
        self.scalars = {k: v for k, v in SCALAR.findall(text)}
        self.is_passive = "Passives" in path.parts

    @property
    def fields(self):
        return class_fields(self.cls)


def load_assets():
    """{m_Name: [Asset, ...]} for every .asset under Data."""
    out = {}
    for p in DATA.rglob("*.asset"):
        t = p.read_text(encoding="utf-8", errors="replace")
        if NAME.search(t):
            a = Asset(p, t)
            out.setdefault(a.name, []).append(a)
    return out


def guid_names(assets):
    g = {}
    for lst in assets.values():
        for a in lst:
            meta = Path(str(a.path) + ".meta")
            if meta.exists():
                m = re.search(r"^guid: ([0-9a-f]{32})", meta.read_text(encoding="utf-8"), re.M)
                if m:
                    g[m.group(1)] = a.name
    return g


def registry(assets):
    """Names listed in AbilityRegistry.asset (abilities and passives), the set a delta can address."""
    g = guid_names(assets)
    t = (DATA / "AbilityRegistry.asset").read_text(encoding="utf-8")
    return {g[x] for x in GUID.findall(t) if x in g}


def kit_of(asset, guid_to_name):
    if "Kit:" not in asset.text:
        return []
    return [guid_to_name.get(x, "?") for x in GUID.findall(asset.text.split("Kit:")[1])]
